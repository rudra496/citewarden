// anchor cannot exist yet.
export const USC_VOL_MAX = 605;

export function eraYearForVolume(vol) {
  if (vol <= ERA_ANCHORS[0][0]) return ERA_ANCHORS[0][1];
  for (let i = 0; i < ERA_ANCHORS.length - 1; i++) {
    const [v0, y0] = ERA_ANCHORS[i];
    const [v1, y1] = ERA_ANCHORS[i + 1];
    if (vol >= v0 && vol <= v1) {
      const t = (vol - v0) / (v1 - v0);
      return Math.round(y0 + t * (y1 - y0));
    }
  }
  return ERA_ANCHORS[ERA_ANCHORS.length - 1][1];
}

