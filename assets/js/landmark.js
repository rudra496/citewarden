let _cases = null, _ukEu = null;

// Synchronous injection (tests, SSR). Both args optional.
export function setReferenceData({ landmarks, ukEu }) {
  if (landmarks) _cases = landmarks;
  if (ukEu) _ukEu = ukEu;
}

export async function loadReferenceData() {
  if (!_cases) {
    const r = await fetch("assets/js/data/landmarks.json");
    _cases = await r.json();
  }
  if (!_ukEu) {
    const r = await fetch("assets/js/data/uk_eu_acts.json");
    _ukEu = await r.json();
  }
  return { landmarks: _cases, ukEu: _ukEu };
}

const norm = (s) => s.toLowerCase().replace(/\s+/g, " ").trim();

export function findLandmarkByCite(vol, page) {
  if (!_cases) return null;
  const cite = `${vol} U.S. ${page}`;
  return _cases.cases.find((c) => c.cite === cite) || null;
}

export function findLandmarkByName(name) {
  if (!_cases) return null;
  const key = norm(name);
  return (
    _cases.cases.find((c) => norm(c.name) === key) ||
    _cases.cases.find((c) => {
      const cn = norm(c.name);
      return cn.length > 8 && (cn.includes(key) || key.includes(cn));
    }) ||
    null
  );
}

export function matchKnownFabricated(claimant, defendant) {
  const squash = (s) => s.toLowerCase().replace(/[^a-z0-9]/g, "");
  const c = squash(claimant), d = squash(defendant);
  return (
    KNOWN_FABRICATED.find((f) => {
      const m = f.name.match(/^(.*?)\s+v\.\s+(.*)$/);
      if (!m) return false;
      return squash(m[1]) === c && squash(m[2]) === d;
    }) || null
  );
}

export function findUKAct(name, year) {
  if (!_ukEu) return null;
  const n = norm(name);
  return (
    _ukEu.uk.find((a) => norm(a.name) === n && a.year === year) ||
    _ukEu.uk.find((a) => norm(a.name) === n) ||
    null
  );
}

export function findEUAct(cite) {
  if (!_ukEu) return null;
  const squash = (s) => s.toLowerCase().replace(/[^a-z0-9]/g, "");
  const c = squash(cite);
  return _ukEu.eu.find((a) => squash(a.eli) === c.replace("regulationeu", "").replace("eu", "")) ||
         _ukEu.eu.find((a) => c.includes(squash(a.eli))) || null;
}
